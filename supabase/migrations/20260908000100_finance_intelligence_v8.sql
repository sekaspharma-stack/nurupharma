ALTER TABLE public.inventaire ADD COLUMN IF NOT EXISTS categorie text NOT NULL DEFAULT 'Non classé';
ALTER TABLE public.tickets ADD COLUMN IF NOT EXISTS mode_paiement text NOT NULL DEFAULT 'ESPECES';
ALTER TABLE public.tickets ADD COLUMN IF NOT EXISTS client_id bigint;
ALTER TABLE public.tickets ADD COLUMN IF NOT EXISTS montant_paye numeric NOT NULL DEFAULT 0;
ALTER TABLE public.tickets ADD COLUMN IF NOT EXISTS montant_credit numeric NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.clients (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  nom text NOT NULL,
  telephone text DEFAULT '',
  adresse text DEFAULT '',
  actif boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE
);
ALTER TABLE public.clients ENABLE ROW LEVEL SECURITY;
CREATE INDEX IF NOT EXISTS idx_clients_tenant ON public.clients(tenant_id);

CREATE TABLE IF NOT EXISTS public.paiements (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  ticket_id text REFERENCES public.tickets(id) ON DELETE SET NULL,
  client_id bigint REFERENCES public.clients(id) ON DELETE SET NULL,
  montant numeric NOT NULL CHECK (montant > 0),
  mode text NOT NULL,
  observation text DEFAULT '',
  assistant text DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE
);
ALTER TABLE public.paiements ENABLE ROW LEVEL SECURITY;
CREATE INDEX IF NOT EXISTS idx_paiements_tenant ON public.paiements(tenant_id);
CREATE INDEX IF NOT EXISTS idx_paiements_ticket ON public.paiements(ticket_id);
CREATE INDEX IF NOT EXISTS idx_paiements_client ON public.paiements(client_id);

CREATE TABLE IF NOT EXISTS public.mouvements_caisse (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  type text NOT NULL CHECK (type IN ('ENTREE','SORTIE')),
  montant numeric NOT NULL CHECK (montant > 0),
  mode text NOT NULL DEFAULT 'ESPECES',
  motif text DEFAULT '',
  ticket_id text,
  client_id bigint REFERENCES public.clients(id) ON DELETE SET NULL,
  assistant text DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE
);
ALTER TABLE public.mouvements_caisse ENABLE ROW LEVEL SECURITY;
CREATE INDEX IF NOT EXISTS idx_caisse_tenant_created ON public.mouvements_caisse(tenant_id, created_at DESC);

